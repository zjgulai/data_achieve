"""Collector routes: list registered collectors + platform capability catalog.

Catalog covers representative Actors from the 2026-08-12 Apify exploration
(56 original + 22 new: PR media monitoring + remaining ecommerce/B2B actors),
plus TikHub social endpoints and internal collectors (GitHub, RSS).
Organised into 10 groups:
  tikhub_social   – TikHub REST API (TikTok/Instagram/XHS/YouTube/Reddit/X/Threads/LinkedIn/Lemon8)
  apify_social    – P0 social platforms (Instagram, Facebook, TikTok, YouTube, X, Reddit)
  apify_ecommerce – P0/P1 ecommerce & reviews (Amazon, Walmart, eBay, Etsy, Shopify …)
  apify_google    – Google ecosystem (Search, Maps, Trends, News, AI Overviews …)
  apify_ai_search – AI-native search (ChatGPT, Perplexity, Gemini)
  apify_ads       – Ad intelligence (Meta Ads, Google Ads, TikTok Ads, Snap Ads)
  apify_b2b       – B2B/jobs/content (LinkedIn, Hacker News, Bluesky, Telegram, Indeed …)
  apify_media     – PR media monitoring (Forbes/Consumer Reports/Parents/Babylist …)
  apify_open_web  – Generic web crawling (Website Content Crawler, Web Scraper, RAG)
  github          – GitHub REST API
  rss_web         – RSS / public web snapshots
"""

